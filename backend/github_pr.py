import os
import time
from pathlib import Path

from dotenv import load_dotenv
from github import Auth, Github, GithubException

load_dotenv()

ART = Path("artifacts")
ART_BRANCH = "omnisight-artifacts"  # screenshots yahan jaate hain, main code se alag


def github_ready():
    return bool(os.getenv("GITHUB_TOKEN") and os.getenv("GITHUB_REPO"))


def _repo():
    gh = Github(auth=Auth.Token(os.environ["GITHUB_TOKEN"]))
    return gh.get_repo(os.environ["GITHUB_REPO"])


def read_source(path):
    """GitHub ki default branch se file ka asli content padho."""
    repo = _repo()
    f = repo.get_contents(path, ref=repo.default_branch)
    return f.decoded_content.decode("utf-8")


def _ensure_branch(repo, name):
    try:
        repo.get_git_ref(f"heads/{name}")
    except GithubException:
        base = repo.get_branch(repo.default_branch)
        repo.create_git_ref(ref=f"refs/heads/{name}", sha=base.commit.sha)


def _upload(repo, path, local_file, branch, message):
    data = Path(local_file).read_bytes()
    existing = None
    try:
        existing = repo.get_contents(path, ref=branch)
    except GithubException:
        pass
    if existing:
        repo.update_file(path, message, data, existing.sha, branch=branch)
    else:
        repo.create_file(path, message, data, branch=branch)


def open_fix_pr(run_id, finding_id, rel_path, new_content, issue, attempts,
                page_name, viewport, before_img, after_img, summary):
    repo = _repo()
    base = repo.get_branch(repo.default_branch)

    # 1) Naya branch
    branch = f"omnisight/fix-run{run_id}-f{finding_id}"
    try:
        repo.create_git_ref(ref=f"refs/heads/{branch}", sha=base.commit.sha)
    except GithubException:
        branch += f"-{int(time.time())}"
        repo.create_git_ref(ref=f"refs/heads/{branch}", sha=base.commit.sha)

    # 2) Fixed file commit karo
    current = repo.get_contents(rel_path, ref=branch)
    issue_type = issue.get("type", "ui-bug")
    repo.update_file(
        rel_path, f"fix(ui): {issue_type} on {page_name} ({viewport})",
        new_content, current.sha, branch=branch,
    )

    # 3) Screenshots alag branch par daalo
    _ensure_branch(repo, ART_BRANCH)
    folder = f"run-{run_id}/finding-{finding_id}"
    _upload(repo, f"{folder}/before.png", ART / before_img, ART_BRANCH, "OmniSight: before screenshot")
    _upload(repo, f"{folder}/after.png", ART / after_img, ART_BRANCH, "OmniSight: after screenshot")
    img = f"https://github.com/{repo.full_name}/blob/{ART_BRANCH}/{folder}"

    # 4) Pull Request kholo
    body = f"""## OmniSight automated UI fix

**Issue:** {issue.get('description')}
**Type / severity:** `{issue_type}` / `{issue.get('severity')}`
**Page / viewport:** `{page_name}` / `{viewport}`
**Verification:** fix was applied in a headless browser and a vision model confirmed it
(attempts needed: {attempts}).
**Change:** {summary}

### Before
![before]({img}/before.png?raw=true)

### After (live fix, verified)
![after]({img}/after.png?raw=true)

---
*Generated by OmniSight. Please review the diff before merging.*
"""
    pr = repo.create_pull(
        title=f"[OmniSight] Fix {issue_type} on {page_name} ({viewport})",
        body=body, head=branch, base=repo.default_branch,
    )
    return pr.html_url, pr.number


def merge_pr(pr_number):
    pr = _repo().get_pull(pr_number)
    if pr.merged:
        return "already merged"
    pr.merge(merge_method="squash")
    return "merged"


def close_pr(pr_number):
    pr = _repo().get_pull(pr_number)
    if pr.merged or pr.state == "closed":
        return "already closed"
    pr.edit(state="closed")
    return "closed"